  window.sendsongApplyCopy = function (lang) {
    var table = copy[lang] || copy.it;
    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var key = el.getAttribute('data-i18n');
      if (!Object.prototype.hasOwnProperty.call(table, key)) continue;
      if (el.hasAttribute('data-i18n-html')) el.innerHTML = table[key];
      else el.textContent = table[key];
    }
    var alts = document.querySelectorAll('[data-i18n-alt]');
    for (var a = 0; a < alts.length; a++) {
      var altKey = alts[a].getAttribute('data-i18n-alt');
      if (Object.prototype.hasOwnProperty.call(table, altKey)) alts[a].setAttribute('alt', table[altKey]);
    }
    var arias = document.querySelectorAll('[data-i18n-aria]');
    for (var r = 0; r < arias.length; r++) {
      var ariaKey = arias[r].getAttribute('data-i18n-aria');
      if (Object.prototype.hasOwnProperty.call(table, ariaKey)) arias[r].setAttribute('aria-label', table[ariaKey]);
    }
  };
